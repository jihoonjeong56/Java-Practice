package org.example.chapter01;

public class D_Semicolon {
    public static void main(String[] args) {
        // === 세미콜론(;) ===
        // 코드 명령어단위를 한 줄에 한 문장씩 작성을 원칙
        // -> 세미콜론이 한 문장의 끝마침을 의미
        int semi;
        int colon;
        // 이런 사용은 권하지 않는다

        // 콤마(, )로 구분 가능
        int a;
        int b;
        int c;
        int aa, bb, cc;
        aa = 10;
        bb = 20;
        cc = 30; // 초기화는 개별적으로!
    }
}
